"""ReportPresenter adapter: console review screens and Markdown reports."""
from __future__ import annotations

from collections.abc import Mapping, Sequence

from ..application.contracts import LEDGER_HEADING
from ..application.documents import PostmortemView, ReviewView
from ..domain.automation import ActionTiering, AutomationTier
from ..domain.review import IncidentFinalState

AI_TAG = "[AI-INFERRED – unverified]"


class MarkdownPresenter:
    # -- operator console ------------------------------------------------------------
    def review_screen(self, view: ReviewView) -> str:
        lines = ["", "=" * 78, "OPERATOR REVIEW — AI-GENERATED RECOMMENDATIONS (nothing has been executed)", "=" * 78]
        for inc in view.incidents:
            iid = inc.incident_id
            c, plan, blast = view.classifications[iid], view.plans[iid], view.blast[iid]
            lines += [
                "",
                f"[{iid}] class={c.incident_class}  urgency={c.urgency}  confidence={c.confidence.value}  "
                f"blast_radius={blast.blast_radius_score} ({blast.band})",
                f"  primary={inc.primary_service}  impacted={', '.join(inc.impacted_services)}  region={inc.region}  "
                f"deploy_signal={'yes' if inc.contains_deploy_signal else 'no'}",
                f"  suspected root cause (AI): {c.suspected_root_cause}",
                "  recommended actions:",
            ]
            for a in plan.recommended_actions:
                gate = "[NEEDS HUMAN APPROVAL]" if a.requires_human_approval else "[policy: no approval required]"
                lines += [f"    - {a.action:<34} {gate}", f"        why: {a.reason}"]
            lines += [f"    x {r.action:<34} [FILTERED BY POLICY] {r.reason}" for r in plan.policy_rejected_actions]
            lines += [f"    ~ {a.action:<34} [AI chose to avoid] {a.reason}" for a in plan.explicitly_avoided_actions]
        lines += ["", "-" * 78, view.prompt]
        return "\n".join(lines)

    def review_summary(self, final_states: Mapping[str, IncidentFinalState]) -> str:
        lines = ["", "Post-review state:"]
        for iid, st in final_states.items():
            override = f" (overridden from {st.original_urgency})" if st.urgency_overridden else ""
            lines.append(f"  {iid}: urgency={st.final_urgency}{override}")
            lines += [f"    {o.status.value:<24} {o.action}" + (f"  — {o.note}" if o.note else "") for o in st.actions]
        return "\n".join(lines)

    # -- incident brief ------------------------------------------------------------------
    def incident_brief(self, body: str, final_states: Mapping[str, IncidentFinalState], provider_label: str, generated_at: str) -> str:
        header = "\n".join([
            "# Incident Brief",
            "",
            f"> **AI-generated briefing ({provider_label}), generated {generated_at} after operator review.**",
            "> No infrastructure actions have been executed by this system. Status vocabulary:",
            "> **approved** = explicitly approved by the operator · **auto_cleared_by_policy** = policy permits without approval (operator did not reject) ·",
            "> **pending_approval** = awaiting a human · **rejected** = rejected by the operator · **invalidated_by_override** = made impermissible by an urgency override.",
            "> The *Authoritative Action Ledger* at the end is generated by code from `operator_decisions.json` and is the system of record.",
            "",
        ])
        return header + "\n" + body.strip() + "\n\n" + self._ledger(final_states) + "\n"

    @staticmethod
    def _ledger(final_states: Mapping[str, IncidentFinalState]) -> str:
        rows = [f"## {LEDGER_HEADING}", "",
                "_Generated deterministically from `operator_decisions.json`; this table overrides any AI-written text above._", ""]
        for iid, st in final_states.items():
            override = f" (operator override from {st.original_urgency})" if st.urgency_overridden else ""
            rows += [f"### {iid} — `{st.incident_class}` — final urgency **{st.final_urgency}**{override}", "",
                     "| Action | Status | Human approval required | Decided by | Origin | Note |", "|---|---|---|---|---|---|"]
            rows += [f"| `{o.action}` | **{o.status.value}** | {'yes' if o.requires_human_approval else 'no'} | {o.decided_by} | "
                     f"{o.origin.value} | {o.note or '—'} |" for o in st.actions]
            rows += [f"| `{p.action}` | **filtered_by_policy** | — | policy | ai_recommendation | {p.reason} |"
                     for p in st.policy_rejected_actions]
            rows.append("")
        return "\n".join(rows)

    # -- safe automation plan --------------------------------------------------------------
    def automation_plan(self, tiers: Sequence[ActionTiering], narrative: str | None, provider_label: str) -> str:
        titles = {
            AutomationTier.FULL: "Fully Automatable",
            AutomationTier.CONDITIONAL: "Conditionally Automatable (with guardrails)",
            AutomationTier.NEVER: "Never Automate (in this scenario)",
        }
        lines = ["# Safe Automation Plan", "",
                 "> Tiers below are **computed deterministically** from `runbook_policy.json` and this run's incidents and operator decisions.",
                 "> Nothing here enables automation; it is a recommendation for future control-plane design.", ""]
        for tier, title in titles.items():
            lines += [f"## {title}", ""]
            rows = [t for t in tiers if t.tier is tier]
            if not rows:
                lines += ["_None._", ""]
            for t in rows:
                lines += [f"### `{t.action}`",
                          f"- Policy: human approval {'required' if t.policy_requires_human_approval else 'not required'}; "
                          f"allowed if {list(t.max_allowed_if) if t.max_allowed_if is not None else 'no policy entry'}",
                          f"- Rationale: {t.rationale}"]
                if t.guardrails:
                    lines.append(f"- Guardrails: {t.guardrails}")
                observed = ", ".join(t.observed_in_incidents) or "not recommended"
                rejected = f"; operator rejected in {', '.join(t.operator_rejected_in)}" if t.operator_rejected_in else ""
                lines += [f"- Observed this run: {observed}{rejected}", ""]
        lines += ["## Promotion Criteria (any tier change)", "",
                  "- Shadow mode first: log what automation *would* have done next to the operator decision for at least 20 incidents.",
                  "- Promote only when agreement is at least 95% with zero unsafe recommendations; demote automatically on any operator override.",
                  "- Every automated action must emit an audit record and have a one-command revert.", ""]
        if narrative:
            lines += [f"## AI Commentary ({provider_label}, AI-generated, not policy)", "", narrative.strip(), ""]
        return "\n".join(lines)

    # -- postmortem --------------------------------------------------------------------------
    def postmortem(self, view: PostmortemView, provider_label: str) -> str:
        lines = ["# Postmortem Template", "",
                 f"> Pre-filled automatically. Lines tagged **{AI_TAG}** come from {provider_label} and must be verified by the incident owner.",
                 "> Everything else (timeline, decisions, evidence list) is derived deterministically from pipeline artifacts.", ""]
        for item in view.incidents:
            inc, st, c, inf = item.incident, item.final_state, item.classification, item.inference
            lines += [f"## {inc.incident_id} — {st.incident_class} — final urgency {st.final_urgency}", "",
                      f"**Owner:** _TBD_ · **Status:** Draft · **Region:** {inc.region}", "",
                      "### Timeline (from alerts and the review log)", "",
                      "| Time (UTC) | Service | Severity | Signal |", "|---|---|---|---|"]
            for a in item.alerts:
                ts = a.model_dump(mode="json")["ts"]
                lines.append(f"| {ts} | {a.service} | {a.severity.value} | {a.metric}={a.observed_value:g} (threshold {a.threshold:g}): {a.message} |")
            lines += ["", f"- Operator decisions: approved {list(st.approved_actions) or 'none'}; rejected {list(st.rejected_actions) or 'none'}; "
                          f"urgency {st.original_urgency} → {st.final_urgency}.", "",
                      "### Probable Contributing Factors", "",
                      f"- {AI_TAG} Suspected root cause (confidence {c.confidence.value}): {c.suspected_root_cause}"]
            lines += [f"- {AI_TAG} {x}" for x in inf["contributing_factors"]]
            lines += [f"- Correlation basis (deterministic): {', '.join(inc.correlation_basis)}", "", "### Evidence Still To Gather", ""]
            lines += [f"- [ ] {g}" for g in item.evidence_gaps]
            lines += ["", "### Prevention Ideas", "", "**Architecture**"] + [f"- {AI_TAG} {x}" for x in inf["prevention_architecture"]]
            lines += ["", "**Observability**"] + [f"- {AI_TAG} {x}" for x in inf["prevention_observability"]]
            lines += ["", "**Process**"] + [f"- {AI_TAG} {x}" for x in inf["prevention_process"]]
            lines += ["", "### Action Items", "", "| Item | Owner | Due |", "|---|---|---|", "| _TBD_ | | |", ""]
        return "\n".join(lines)
